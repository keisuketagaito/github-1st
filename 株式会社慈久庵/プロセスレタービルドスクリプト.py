def set_lines(shape, lines, heads=()):
    """本文を差し替える。見出し行は1段落目（下線付き）、本文行は3段落目の書式を複製する。

    テンプレートの1段落目は下線・アクセント色の見出しであるため、
    全行をその書式で複製すると資料全体が下線だらけになる。
    """
    tf = shape.text_frame
    paras = tf.paragraphs

    def _proto(i):
        el = copy.deepcopy(paras[i]._p)
        for r in el.findall(qn('a:r'))[1:]:
            el.remove(r)
        return el

    proto_head, proto_body = _proto(0), _proto(2)
    body = tf._txBody
    for el in body.findall(qn('a:p')):
        body.remove(el)
    for ln in lines:
        el = copy.deepcopy(proto_head if ln in heads else proto_body)
        r = el.find(qn('a:r'))
        if r is None:
            body.append(el)
            continue
        r.find(qn('a:t')).text = ln
        body.append(el)


