def title(ws, text, sub):
    ws['A1'] = text
    ws['A1'].font = Font(name=JP, size=16, bold=True, color='FFFFFFFF')
    ws['A1'].fill = PatternFill('solid', fgColor=NAVY)
    ws['A1'].alignment = Alignment(horizontal='left', vertical='center')
    ws.row_dimensions[1].height = 28
    ws['A2'] = sub
    ws['A2'].font = Font(name=JP, size=10, color=NAVY)
    ws['A2'].alignment = Alignment(wrap_text=False)


def band(ws, row, text, width=1):
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name=JP, size=10, bold=True, color='FFFFFFFF')
    c.fill = PatternFill('solid', fgColor=BLUE)
    for j in range(2, width + 1):
        ws.cell(row=row, column=j).fill = PatternFill('solid', fgColor=BLUE)


def header(ws, row, labels, fill=NAVY):
    for j, t in enumerate(labels, start=1):
        c = ws.cell(row=row, column=j, value=t)
        c.font = Font(name=JP, size=10, bold=True, color='FFFFFFFF')
        c.fill = PatternFill('solid', fgColor=fill)
        c.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        c.border = BB
    ws.row_dimensions[row].height = 30


def body(ws, row, values, input_cols=(), fc=None, fill=None, h=None):
    for j, v in enumerate(values, start=1):
        c = ws.cell(row=row, column=j, value=v)
        if j in input_cols:
            c.font = Font(name=JP, size=10, color=INPUT_FC)
            c.fill = PatternFill('solid', fgColor=INPUT_BG)
        else:
            c.font = Font(name=JP, size=10, color=fc or 'FF000000')
            if fill:
                c.fill = PatternFill('solid', fgColor=fill)
        c.alignment = Alignment(vertical='top', wrap_text=True)
        c.border = BB
    if h:
        ws.row_dimensions[row].height = h


def widths(ws, spec):
    for col, w in spec.items():
        ws.column_dimensions[col].width = w


