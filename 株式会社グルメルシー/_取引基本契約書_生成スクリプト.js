const FONT = { name: "ＭＳ 明朝", eastAsia: "ＭＳ 明朝" };
const GOTHIC = { name: "ＭＳ ゴシック", eastAsia: "ＭＳ ゴシック" };
const SZ = 21;      // 10.5pt
const SZ_S = 16;    // 8pt
const SZ_XS = 15;   // 7.5pt

const run = (text, opts = {}) =>
  new TextRun({ text, font: opts.bold ? GOTHIC : FONT, size: opts.size || SZ, bold: !!opts.bold });

const P = (text, opts = {}) =>
  new Paragraph({
    children: Array.isArray(text) ? text : [run(text, opts)],
    alignment: opts.align,
    indent: opts.indent,
    spacing: { after: opts.after === undefined ? 60 : opts.after, line: opts.line || 280 },
    keepNext: opts.keepNext,
  });

// ---------------------------------------------------------------- table utils
const NO_PAD = { top: 40, bottom: 40, left: 80, right: 80 };
const cell = (children, opts = {}) =>
  new TableCell({
    children,
    width: { size: opts.w, type: WidthType.DXA },
    columnSpan: opts.span,
    verticalAlign: VerticalAlign.CENTER,
    margins: NO_PAD,
    shading: opts.head ? { type: ShadingType.CLEAR, fill: "EFEFEF" } : undefined,
  });

const tcell = (text, opts = {}) =>
  cell([P(text, { size: opts.size || SZ_S, bold: opts.head, align: opts.align, after: 0, line: 180 })], opts);

const table = (widths, rows) =>
  new Table({
    columnWidths: widths,
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    rows,
  });

// ------------------------------------------------------------- article engine
class Body {
  constructor() { this.n = 0; this.refs = {}; this.arts = []; }
  // clauses は配列、又は本文確定後に評価される関数（条番号の相互参照用）
  art(key, title, clauses) {
    this.n += 1;
    this.refs[key] = this.n;
    this.arts.push({ n: this.n, title, clauses });
    return this;
  }
  ref(key) { return `第${this.refs[key]}条`; }
  render() {
    const out = [];
    this.arts.forEach(({ n, title, clauses }) => {
      const list = typeof clauses === "function" ? clauses(this) : clauses;
      out.push(P(`第${n}条（${title}）`, { bold: true, after: 40, keepNext: true }));
      const multi = list.length > 1;
      list.forEach((c, i) => {
        const isObj = typeof c === "object";
        const text = isObj ? c.t : c;
        out.push(P((multi ? `${i + 1}　` : "") + text, {
          indent: multi ? { left: 300, hanging: 300 } : undefined,
          after: 40,
        }));
        if (isObj && c.items) {
          c.items.forEach((it, j) => {
            out.push(P(`(${j + 1})　${it}`, { indent: { left: 640, hanging: 340 }, after: 20 }));
          });
        }
      });
      out.push(P("", { after: 60 }));
    });
    return out;
  }
}

