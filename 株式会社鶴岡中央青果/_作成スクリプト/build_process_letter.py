def fill(sh, lines):
    tb = sh.text_frame._txBody
    ps = tb.findall(qn('a:p'))
    head = ps[0]                                   # 見出し（下線あり）
    tmpl = next(p for p in ps[1:] if p.findall(qn('a:r')))   # 本文（下線なし）
    empty = next(p for p in ps if not p.findall(qn('a:r')))
    for p in ps:
        tb.remove(p)
    for ln in lines:
        if not ln:
            tb.append(copy.deepcopy(empty)); continue
        p = copy.deepcopy(head if ln[:2] in ('1.', '2．', '3.', '4.') else tmpl)
        rs = p.findall(qn('a:r'))
        for r in rs[1:]:
            p.remove(r)
        rs[0].find(qn('a:t')).text = ln
        tb.append(p)
for sh in s.shapes:
    if sh.shape_id == 13: fill(sh, LEFT)
    if sh.shape_id == 14: fill(sh, RIGHT)
