const FONT = '游ゴシック', NAVY = '1F3864', BLUE = '2E75B6';
const W = 16838, H = 11906, M = 850, TW = W - 2 * M;   // A4横

const run = (t, o = {}) => new TextRun({ text: t, font: FONT, size: o.size || 18, bold: o.bold, color: o.color });
const para = (t, o = {}) => new Paragraph({ spacing: { after: o.after ?? 60, line: 300 }, alignment: o.align,
  children: (Array.isArray(t) ? t : [t]).map(x => typeof x === 'string' ? run(x, o) : x) });
const h1 = t => new Paragraph({ spacing: { before: 280, after: 120 },
  border: { bottom: { style: BorderStyle.SINGLE, size: 8, color: NAVY, space: 2 } },
  children: [run(t, { size: 26, bold: true, color: NAVY })] });
const h2 = t => new Paragraph({ spacing: { before: 200, after: 80 }, children: [run(t, { size: 22, bold: true, color: BLUE })] });
const bullet = t => new Paragraph({ numbering: { reference: 'sq', level: 0 }, spacing: { after: 40, line: 300 }, children: [run(t)] });

const bd = { style: BorderStyle.SINGLE, size: 4, color: 'A6A6A6' };
const borders = { top: bd, bottom: bd, left: bd, right: bd };
function cell(text, w, o = {}) {
  const lines = String(text).split('\n');
  return new TableCell({ width: { size: w, type: WidthType.DXA }, borders, verticalAlign: o.v || VerticalAlign.TOP,
    shading: o.fill ? { type: ShadingType.CLEAR, color: 'auto', fill: o.fill } : undefined,
    margins: { top: 60, bottom: 60, left: 90, right: 90 },
    children: lines.map(l => new Paragraph({ alignment: o.align, spacing: { after: 20, line: 280 },
      children: [run(l, { size: o.size || 17, bold: o.bold, color: o.color })] })) });
}
function table(cols, head, rows) {
  const hr = new TableRow({ tableHeader: true, children: head.map((h, i) =>
    cell(h, cols[i], { fill: NAVY, color: 'FFFFFF', bold: true, align: AlignmentType.CENTER, v: VerticalAlign.CENTER })) });
  const body = rows.map(r => new TableRow({ cantSplit: true, children: r.map((v, i) =>
    cell(v, cols[i], { align: i <= 1 && cols.length === 5 ? AlignmentType.CENTER : (i === 0 ? AlignmentType.CENTER : undefined),
      fill: i === 1 && v === '高' ? 'FCE4D6' : undefined, bold: i === 1 && v === '高' })) }));
  return new Table({ width: { size: TW, type: WidthType.DXA }, columnWidths: cols, rows: [hr, ...body] });
}

