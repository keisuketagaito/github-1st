    eq('流動負債', [sum(BS_L[r][1][i] for r in range(6, 14)) for i in range(4)], BS_L_SUB['流動負債'])
    eq('純資産', [sum(BS_L[r][1][i] for r in (36, 44, 45)) for i in range(4)], BS_L_SUB['純資産'])
    eq('負債純資産=資産', [sum(v[1][i] for v in BS_L.values()) for i in range(4)], BS_A_TOTAL)
    sales = [sum(PL[r][1][i] for r in (5, 6, 10)) for i in range(4)]
    eq('売上高', sales, PL_CHECK['売上高'])
    op = [sales[i] - PL_CHECK['売上原価'][i] - SGA_TOTAL[i] for i in range(4)]
    eq('営業利益', op, PL_CHECK['営業利益'])
    rec = [op[i] + sum(PL[r][1][i] for r in (21, 22, 23, 26)) - sum(PL[r][1][i] for r in (29, 30, 31)) for i in range(4)]
    eq('経常利益', rec, PL_CHECK['経常利益'])
    ni = [rec[i] + PL[39][1][i] - PL[53][1][i] for i in range(4)]
    eq('当期純利益', ni, PL[58][1])
    return ng


