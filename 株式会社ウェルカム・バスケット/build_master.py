    def put(sheet, rows, cols):
        for r, (label, vals) in rows.items():
            try:
                b.set_cell(sheet, 'B%d' % r, label if label else None)
            except KeyError:                 # 見出しセルの無い行（PL58行のチェック用入力等）
                pass
            for c, i in zip(cols, range(4)):
                b.set_cell(sheet, '%s%d' % (c, r), None if vals is None else vals[i])
    put('BS(借方)', BS_A, cols5)
